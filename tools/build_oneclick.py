#!/usr/bin/env python3
"""Stage and optionally compile the private, one-file JarvisOneClick.exe.

This builder runs on a Windows build machine. It never commits upstream source,
secrets, certificates, databases, or the compiled executable to Git.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from oneclick import core, frozen, win  # noqa: E402
from tools import build_package  # noqa: E402

DEFAULT_OUT = ROOT / ".build" / "oneclick"
ENTRY = ROOT / "oneclick" / "main.py"
EXE_NAME = "JarvisOneClick"

COLLECT_PACKAGES = (
    "fastapi", "starlette", "uvicorn", "pydantic", "pydantic_core",
    "httpx", "httpcore", "websockets", "anyio", "h11", "sniffio",
    "click", "yaml", "python_dotenv", "colorama", "watchfiles",
    "httptools", "uvloop", "playwright", "PIL",
)

BASE_HIDDEN_IMPORTS = (
    "server", "jarvis_mcp", "claude_env", "uvicorn.logging",
    "uvicorn.protocols.http.httptools_impl",
    "uvicorn.protocols.websockets.websockets_impl",
    "oneclick.main", "oneclick.gui", "oneclick.frozen",
    "oneclick.patches", "oneclick.win", "oneclick.core",
    "jarvis_win.hook", "jarvis_win.sitecustomize",
)


def payload_hidden_imports(app_dir: Path) -> list[str]:
    """Every top-level upstream module plus every jarvis_win module."""
    names = {path.stem for path in app_dir.glob("*.py")
             if path.stem.isidentifier()}
    package = app_dir / "jarvis_win"
    if package.is_dir():
        names |= {"jarvis_win." + path.stem for path in package.glob("*.py")
                  if path.stem.isidentifier()}
    return sorted(names)


def render_spec(*, entry: Path, app_dir: Path, browsers: Path,
                hidden_imports: list[str]) -> str:
    """Return a one-file, windowed PyInstaller spec without importing it."""
    lines = [
        "# -*- mode: python ; coding: utf-8 -*-",
        "# Generated by tools/build_oneclick.py. Do not commit.",
        "from PyInstaller.utils.hooks import collect_all",
        "",
        "block_cipher = None",
        "packages = " + repr(list(COLLECT_PACKAGES)),
        "datas = [(" + repr(str(app_dir)) + ", 'app'), ("
        + repr(str(browsers)) + ", 'ms-playwright')]",
        "binaries = []",
        "hiddenimports = " + repr(hidden_imports),
        "for package in packages:",
        "    try:",
        "        collected_datas, collected_binaries, collected_hidden = collect_all(package)",
        "        datas += collected_datas",
        "        binaries += collected_binaries",
        "        hiddenimports += collected_hidden",
        "    except Exception:",
        "        pass",
        "hiddenimports = list(dict.fromkeys(hiddenimports))",
        "",
        "a = Analysis(",
        "    [" + repr(str(entry)) + "],",
        "    pathex=[" + repr(str(ROOT)) + ", " + repr(str(app_dir)) + "],",
        "    binaries=binaries,",
        "    datas=datas,",
        "    hiddenimports=hiddenimports,",
        "    hookspath=[],",
        "    hooksconfig={},",
        "    runtime_hooks=[],",
        "    excludes=['pytest', 'pytest_asyncio'],",
        "    win_no_prefer_redirects=False,",
        "    win_private_assemblies=False,",
        "    cipher=block_cipher,",
        "    noarchive=False,",
        ")",
        "pyz = PYZ(a.pure, a.zipped_data, cipher=block_cipher)",
        "exe = EXE(",
        "    pyz,",
        "    a.scripts,",
        "    a.binaries,",
        "    a.zipfiles,",
        "    a.datas,",
        "    [],",
        "    name=" + repr(EXE_NAME) + ",",
        "    debug=False,",
        "    bootloader_ignore_signals=False,",
        "    strip=False,",
        "    upx=False,",
        "    upx_exclude=[],",
        "    runtime_tmpdir=None,",
        "    console=False,",
        "    disable_windowed_traceback=False,",
        "    argv_emulation=False,",
        "    target_arch=None,",
        "    codesign_identity=None,",
        "    entitlements_file=None,",
        "    uac_admin=False,",
        "    uac_uiaccess=False,",
        ")",
        "",
    ]
    return "\n".join(lines)


def stage_app(out: Path, payload: Path) -> Path:
    app_dir = out / "app"
    if app_dir.exists():
        shutil.rmtree(app_dir)
    shutil.copytree(payload, app_dir, ignore=shutil.ignore_patterns(
        ".git", "__pycache__", "node_modules", "build",
        "*.iss", "*.exe", "*.pem", "*.db", "*.log", ".env"))
    # Remove only a root-level build output; frontend/dist is required.
    shutil.rmtree(app_dir / "dist", ignore_errors=True)
    # The Inno Setup path is not used by the frozen app.
    shutil.rmtree(app_dir / "installer", ignore_errors=True)
    shutil.rmtree(app_dir / "scripts", ignore_errors=True)
    shutil.rmtree(app_dir / "frontend" / "node_modules", ignore_errors=True)
    shutil.rmtree(app_dir / "data", ignore_errors=True)
    (app_dir / "data").mkdir(parents=True, exist_ok=True)
    (app_dir / "data" / ".gitkeep").write_text("", encoding="utf-8")
    return app_dir


def assert_payload_complete(app_dir: Path) -> None:
    required = (
        "server.py", "jarvis_mcp.py", "jarvis_win/hook.py",
        "jarvis_win/ShowToast.ps1", "frontend/dist/index.html",
        "frontend/dist/dashboard.html", "requirements-windows.txt",
        "UPSTREAM_LICENSE.txt", "INSTALLER_LICENSE.txt",
    )
    missing = [name for name in required if not (app_dir / name).exists()]
    if missing:
        raise RuntimeError("Payload is missing: " + ", ".join(missing))
    problems = core.scan_payload(app_dir)
    if problems:
        raise RuntimeError("Refusing to embed private/generated files: "
                           + ", ".join(problems[:12]))


def locate_openssl(explicit: str | None) -> Path:
    env = dict(os.environ)
    candidates = [explicit, env.get("JARVIS_OPENSSL")]
    for root in (env.get("ProgramFiles"), env.get("ProgramFiles(x86)"),
                 env.get("LOCALAPPDATA")):
        if root:
            candidates.append(str(Path(root) / "Git" / "usr" / "bin" / "openssl.exe"))
            candidates.append(str(Path(root) / "Programs" / "Git" / "usr" / "bin" / "openssl.exe"))
    candidates.append(shutil.which("openssl.exe"))
    for value in candidates:
        if value and core.is_native_exe(value):
            return Path(value)
    raise RuntimeError("A Windows openssl.exe is required; pass --openssl PATH.")


def locate_playwright(explicit: str | None, python: str) -> Path:
    env = dict(os.environ)
    candidates = [explicit, env.get("PLAYWRIGHT_BROWSERS_PATH")]
    local = env.get("LOCALAPPDATA")
    if local:
        candidates.append(str(Path(local) / "ms-playwright"))
    for value in candidates:
        if value and Path(value).is_dir() and any(Path(value).glob("chromium-*")):
            return Path(value)
    result = win.run_hidden([python, "-m", "playwright", "install", "chromium"],
                            timeout=900.0)
    if result.returncode != 0:
        raise RuntimeError("Playwright Chromium could not be installed: "
                           + result.stdout[-500:])
    for value in candidates:
        if value and Path(value).is_dir() and any(Path(value).glob("chromium-*")):
            return Path(value)
    raise RuntimeError("Playwright Chromium was installed but its folder was not found.")


def copy_browsers(source: Path, out: Path) -> Path:
    target = out / "browsers"
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(source, target)
    return target


def write_manifest(out: Path, app_dir: Path, browsers: Path, *,
                   upstream_ref: str, openssl: Path, playwright: Path,
                   frontend_prebuilt: bool) -> dict[str, object]:
    files = core.sha256_manifest(app_dir)
    files += [{"path": "ms-playwright/" + item["path"],
               "sha256": item["sha256"]}
              for item in core.sha256_manifest(browsers)]
    manifest: dict[str, object] = {
        "version": 1,
        "mode": "one-click-frozen",
        "exe_name": EXE_NAME + ".exe",
        "upstream_ref": upstream_ref,
        "frontend_prebuilt": frontend_prebuilt,
        "openssl_bundled": True,
        "openssl_source": str(openssl),
        "playwright_browsers_bundled": True,
        "playwright_source": str(playwright),
        "python_runtime": "embedded",
        "node_runtime": False,
        "venv": False,
        "inno_setup": False,
        "secrets_embedded": False,
        "file_count": len(files),
        "files": files,
    }
    text = core.json_dumps(manifest)
    (out / "ONCLICK_MANIFEST.json").write_text(text, encoding="utf-8")
    (app_dir / "ONCLICK_MANIFEST.json").write_text(text, encoding="utf-8")
    return manifest


def compile_exe(out: Path, python: str) -> Path:
    result = win.run_hidden(
        [python, "-m", "PyInstaller", "--noconfirm", "--clean",
         str(out / (EXE_NAME + ".spec"))],
        cwd=ROOT, timeout=1800.0)
    if result.returncode != 0:
        raise RuntimeError("PyInstaller failed:\n" + result.stdout[-2000:])
    exe = out / "dist" / (EXE_NAME + ".exe")
    if not exe.exists():
        raise RuntimeError("PyInstaller finished but " + str(exe) + " is missing.")
    return exe


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--upstream", help="Private local JARVIS fork")
    parser.add_argument("--ref", help="Override pinned upstream ref")
    parser.add_argument("--frontend-dist", help="Pre-built frontend/dist")
    parser.add_argument("--skip-frontend", action="store_true",
                        help="Test staging only; never compile a release with this")
    parser.add_argument("--openssl", help="Windows openssl.exe to embed")
    parser.add_argument("--playwright", help="Playwright browser directory")
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    parser.add_argument("--python", default=sys.executable)
    parser.add_argument("--compile", action="store_true",
                        help="Run PyInstaller after staging")
    args = parser.parse_args(argv)
    frozen.install_hidden_subprocess_patch()

    if args.compile and args.skip_frontend:
        raise RuntimeError("--compile refuses --skip-frontend: the .exe needs a real frontend/dist.")

    out = Path(args.out).resolve()
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True, exist_ok=True)
    payload_out = out / "payload"

    build_argv = ["--out", str(payload_out)]
    if args.upstream:
        build_argv += ["--upstream", args.upstream]
    if args.ref:
        build_argv += ["--ref", args.ref]
    if args.frontend_dist:
        build_argv += ["--frontend-dist", args.frontend_dist]
    if args.skip_frontend:
        build_argv.append("--skip-frontend")
    build_package.main(build_argv)

    app_dir = stage_app(out, payload_out / "payload")
    openssl = locate_openssl(args.openssl)
    (app_dir / "tools").mkdir(parents=True, exist_ok=True)
    shutil.copy2(openssl, app_dir / "tools" / "openssl.exe")
    assert_payload_complete(app_dir)

    playwright_source = locate_playwright(args.playwright, args.python)
    browsers = copy_browsers(playwright_source, out)

    hidden = sorted(set(BASE_HIDDEN_IMPORTS) | set(payload_hidden_imports(app_dir)))
    spec = render_spec(entry=ENTRY, app_dir=app_dir, browsers=browsers,
                       hidden_imports=hidden)
    (out / (EXE_NAME + ".spec")).write_text(spec, encoding="utf-8")

    upstream = json.loads((ROOT / "upstream.json").read_text(encoding="utf-8"))
    ref = args.ref or upstream["pinned_ref"]
    write_manifest(out, app_dir, browsers, upstream_ref=ref,
                   openssl=openssl, playwright=playwright_source,
                   frontend_prebuilt=not args.skip_frontend)

    print("Staged one-click source:", out)
    print("Embedded payload files:", len(core.sha256_manifest(app_dir)))
    print("Chromium bundled from:", playwright_source)
    print("OpenSSL bundled from:", openssl)
    if args.compile:
        exe = compile_exe(out, args.python)
        print("Built:", exe)
        print("Keep this .exe private/local; it contains upstream JARVIS source.")
    else:
        print("Compile with:", args.python, "-m PyInstaller --noconfirm --clean",
              str(out / (EXE_NAME + ".spec")))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
